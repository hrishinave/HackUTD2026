"""Software Factory Feature Requirements export: one behaviour contract as a Markdown requirement document.

Software Factory requirements are Markdown and its Requirements agent reads documents added to a project, so
this is the integration that works today with no API key. A broken contract's export adds a proposed change,
labelled simulated. Nothing here sends anything anywhere.

Owner: AK (role D). Interface: Pact addendum, task P2.
"""

ROLE_LABEL = {"billing_clerk": "Billing clerk", "medical_coder": "Medical coder",
              "denial_specialist": "Denial specialist", "practice_manager": "Practice manager"}

SUGGESTED_EDIT = {
    "app_gap": "The requirement must be completable in the main flow, without opening a secondary tab",
    "know_how_gap": "The requirement must be discoverable without training",
    "stale_requirement": "Review whether this requirement still applies",
}


def _yn(v) -> str:
    return "yes" if v else "no"


def _cell(v) -> str:
    return "" if v is None else str(v).replace("|", "\\|")


def requirement_markdown(contract: dict, finding: dict | None = None) -> str:
    """The Feature Requirements document for one contract; adds a simulated proposed change when broken."""
    req = contract.get("requirement", {})
    rid, statement = req.get("id", contract["id"]), req.get("statement", "")
    role = contract.get("role", "")
    persona = ROLE_LABEL.get(role, role.replace("_", " ").capitalize())
    out = [f"# {rid}: {statement}", "",
           f"Feature: {req.get('feature', 'unspecified')} · Persona: {persona} · "
           f"Source: Pact behaviour contract {contract['id']}", ""]

    out += ["## Requirement", "", statement, ""]

    out += ["## Evidence", ""]
    for e in contract.get("evidence", []):
        where = f"{e.get('speaker', 'Interviewee')}, {e.get('interview_id', '')} {e.get('timestamp', '')}".rstrip()
        q = f", answer to AI question {e['question_id']}" if e.get("question_id") else ""
        out.append(f'- "{e.get("quote", "")}" ({where}{q})')
    if not contract.get("evidence"):
        out.append("- No interview evidence recorded.")
    out.append("")

    conf = contract.get("confidence", {})
    out += ["## Confidence", "", f"Level: {conf.get('level', 'unknown')}",
            f"Said: {_yn(conf.get('said'))} · Did: {_yn(conf.get('did'))} · Code: {_yn(conf.get('code'))}"]
    if conf.get("note"):
        out.append(f"Note: {conf['note']}")
    out.append("")

    out += ["## Behaviour contract", "", f"Promise: {statement}", "",
            "| metric_id | description | comparator | target | tolerance | unit |",
            "|---|---|---|---|---|---|"]
    for x in contract.get("expectations", []):
        out.append("| " + " | ".join(_cell(x.get(k)) for k in
                                       ("metric_id", "description", "comparator", "target", "tolerance", "unit")) + " |")
    out.append("")
    base = contract.get("baseline") or {}
    vals = base.get("values") or {}
    shown = ", ".join(f"{k} = {v}" for k, v in vals.items()) or "none recorded"
    out.append(f"Baseline ({base.get('source', 'unknown source')}): {shown}.")
    if base.get("note"):
        out.append(f"Baseline note: {base['note']}")
    out.append("")
    events = contract.get("events_required", [])
    out.append("Events to instrument: " + (", ".join(f"`{e}`" for e in events) or "none") + ".")
    w = contract.get("window", {})
    out.append(f"Window: {w.get('period', 'week')}ly, at least {w.get('min_tasks')} tasks and "
               f"{w.get('min_people')} people per window, {w.get('learning_period_weeks')} learning weeks, "
               f"drift after {w.get('consecutive_breaches_for_drift')} consecutive breaches.")
    out += ["", "Monitored version of this requirement's entry in Product Overview › Success Metrics.", ""]

    if finding:
        out += ["## Proposed change", "", "Would be proposed as a tracked suggestion (simulated).", "",
                f"Status: {finding.get('status')} since week {finding.get('first_breach_week')}",
                f"Type: {finding.get('type') or 'unknown'}"]
        if finding.get("explanation"):
            out.append(f"Explanation: {finding['explanation']}")
        edit = SUGGESTED_EDIT.get(finding.get("type"))
        if edit:
            out.append(f"Suggested requirement edit: {edit}.")
        out.append("")

    out.append("Generated by Pact. Synthetic data. Maps onto your configured Feature Document Template.")
    return "\n".join(out) + "\n"
